# Energy equivalent of O2 (J per mL), as elsewhere in the app. Repeated here
# rather than taken from designer.R so this file can be sourced on its own.
SPRINT_EQ_O2 <- 20.9

#' The three published supply curves of a case, in W/kg above rest
#'
#' Closed form, exactly as in Briand et al. (2025): a log-normal alactic term, a
#' bi-exponential lactic term normalised to peak at `pla_max`, and a
#' mono-exponential aerobic term rising to MAP less basal metabolic rate.
sprint_case_supplies <- function(cs, t) {
  k <- SPRINT_CONST
  # Reciprocal of the peak of (1 - e^(-t/k1)) e^(-t/k2), so that pla_max is the
  # ACTUAL peak lactic power rather than a scale factor. This is runrgetics'
  # bi_exponential_knorm() written out -- kept in its algebraic form so the two
  # cannot drift; it is 1/f(t_peak) with t_peak = k1 log(1 + k2/k1).
  knorm <- (k$k1 + k$k2) / (k$k2 * (k$k1 / (k$k1 + k$k2))^(k$k1 / k$k2))

  al <- cs$pal_max * exp(-(log(t) - k$mu)^2 / (2 * k$sigma^2))
  al[!is.finite(al)] <- 0                       # log(0) at the first sample
  list(
    atp_pcr = al,
    glyco   = cs$pla_max * knorm * (1 - exp(-t / k$k1)) * exp(-t / k$k2),
    aerobic = (cs$MAP - k$bmr) * (1 - exp(-t / k$tau_aer))
  )
}

#' Evaluate one sprint case on a time grid
#'
#' @param case Name in [SPRINT_CASES].
#' @param dt Grid step (s). 0.05 by default, not the 0.25 the Gastin cases use:
#'   the alactic term peaks at exp(mu) = 0.67 s and a quarter-second grid walks
#'   straight past it.
#' @return data.frame(time, demand, atp_pcr, glyco, aerobic) in mL O2
#'   equivalent / kg / min, above rest. `demand` is the MEASURED metabolic power;
#'   the three supplies are the fitted partition of it, so they sum to slightly
#'   less than `demand` -- see the header. Nothing is subtracted for resting
#'   metabolism because nothing here includes it: di Prampero's cost of running
#'   is a net cost and the aerobic term already asymptotes to MAP - BMR.
sprint_case <- function(case, dt = 0.05) {
  cs <- SPRINT_CASES[[case]]
  if (is.null(cs)) stop("Unknown sprint case: ", case)
  t <- seq(0, cs$duration, by = dt)
  if (t[length(t)] < cs$duration) t <- c(t, cs$duration)

  s <- sprint_case_supplies(cs, t)
  cvt <- 60 / SPRINT_EQ_O2                       # W/kg -> mL O2/kg/min
  d <- data.frame(
    time    = t,
    demand  = stats::approx(cs$demand_t, cs$demand_p, t, rule = 2)$y * cvt,
    atp_pcr = s$atp_pcr * cvt,
    glyco   = s$glyco   * cvt,
    aerobic = s$aerobic * cvt
  )
  attr(d, "case") <- cs
  d
}

#' A case's aerobic ceiling on the model's ABOVE-REST scale (mL O2/kg/min)
#'
#' MAP is published gross, and the simulator's ceiling is an above-rest flux, so
#' basal metabolic rate comes off it -- the same correction gastin_case_vo2max()
#' makes, arriving from the other direction.
sprint_case_vo2max <- function(case) {
  cs <- SPRINT_CASES[[case]]
  if (is.null(cs)) stop("Unknown sprint case: ", case)
  (cs$MAP - SPRINT_CONST$bmr) * 60 / SPRINT_EQ_O2
}

#' Published energy partition of a case (J/kg and %), and the measured total
#'
#' The shares are of the FITTED total, which is what Briand et al. report; the
#' measured total is carried alongside so the fit residual stays visible.
sprint_case_energies <- function(case, dt = 0.01) {
  d <- sprint_case(case, dt)
  cvt <- SPRINT_EQ_O2 / 60
  trap <- function(y) sum(0.5 * (y[-1] + y[-length(y)]) * diff(d$time)) * cvt
  E <- c(alactic = trap(d$atp_pcr), lactic = trap(d$glyco), aerobic = trap(d$aerobic))
  list(alactic = E[["alactic"]], lactic = E[["lactic"]], aerobic = E[["aerobic"]],
       total = sum(E), demand = trap(d$demand),
       share = 100 * E / sum(E))
}

