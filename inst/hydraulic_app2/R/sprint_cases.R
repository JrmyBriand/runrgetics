# =============================================================================
# SPRINT CASES -- the six Berlin-2009 finals, partitioned by Briand et al. (2025)
#
# Eur J Appl Physiol 125:3521-3541, doi 10.1007/s00421-025-05831-0; the analysis
# is the runrgetics package. These are the sprint counterpart of the Gastin case
# figures in gastin_cases.R, and they plug into the same channel: same columns,
# same units, same above-rest convention.
#
# WHAT IS A CASE HERE. Two different things, and the difference is the point.
#
#   * the DEMAND is a MEASUREMENT -- metabolic power from di Prampero's
#     equivalent-slope method applied to the published split times, flat cost
#     3.8 J/kg/m. This is what the simulator is driven with.
#   * the three SUPPLIES are a MODEL -- Briand et al.'s partition of that same
#     demand into a log-normal alactic term, a bi-exponential lactic term and a
#     mono-exponential aerobic term. This is what the simulator is compared with.
#
# So, unlike the Gastin cases, the three supplies DO NOT sum to the demand: they
# sum to the fitted total, which differs from the measurement by the fit residual
# -- 1.6 to 6.0 W/kg RMSE, and -1.05% to 0.05% of total energy. That gap is
# visible on the figure as daylight between the top dashed line and the demand
# line, and it is the inductive model's own error bar. Do not close it by
# construction -- the whole exercise is to see whether the hydraulic model can
# land on the same partition of a demand neither model chose.
#
# UNITS. Stored natively in W/kg above rest, which is what runrgetics works in.
# sprint_case() converts to mL O2 equivalent / kg / min to match gastin_case(),
# because that is the unit the app's case channel speaks.
#
# GENERATED by data-raw/generate_sprint_cases.R -- do not edit by hand.
# =============================================================================

